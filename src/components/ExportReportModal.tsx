import React, { useState } from 'react';
import { AxisConfig, MaterialPreset, WeaponAnalysisResult } from '../types';
import { formatMOI, convertMOI } from '../lib/inertiaCalculator';
import { Check, Copy, Download, FileText, Printer, X } from 'lucide-react';

interface ExportReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  analysis: WeaponAnalysisResult | null;
  material: MaterialPreset;
  axis: AxisConfig;
  filename: string;
}

export const ExportReportModal: React.FC<ExportReportModalProps> = ({
  isOpen,
  onClose,
  analysis,
  material,
  axis,
  filename,
}) => {
  const [copied, setCopied] = useState<boolean>(false);

  if (!isOpen || !analysis) return null;

  const moiLbIn2 = convertMOI(analysis.moiAxis, 'lb_in2');
  const moiOzIn2 = convertMOI(analysis.moiAxis, 'oz_in2');
  const moiKgM2 = convertMOI(analysis.moiAxis, 'kg_m2');
  const moiGCm2 = convertMOI(analysis.moiAxis, 'g_cm2');

  const reportText = `================================================================================
LNCR WEAPON MOI & DYNAMICS ENGINEERING REPORT
Late Night Combat Robotics · Generated: ${new Date().toLocaleString()}
================================================================================

MODEL & MATERIAL:
--------------------------------------------------------------------------------
File:               ${filename}
Material:           ${material.name}
Density:            ${material.densityGPerCm3.toFixed(3)} g/cm³ (${(material.densityGPerCm3 * 0.0361273).toFixed(4)} lb/in³)

MOMENT OF INERTIA (MOI About Rotation Axis):
--------------------------------------------------------------------------------
I_axis (lb·in²):    ${moiLbIn2.toFixed(4)} lb·in²
I_axis (oz·in²):    ${moiOzIn2.toFixed(3)} oz·in²
I_axis (kg·m²):     ${moiKgM2.toExponential(5)} kg·m² (SI)
I_axis (g·cm²):     ${moiGCm2.toFixed(2)} g·cm²

MASS & VOLUME PROPERTIES:
--------------------------------------------------------------------------------
Total Mass:         ${(analysis.totalMassGrams * 0.00220462).toFixed(3)} lb (${(analysis.totalMassGrams * 0.035274).toFixed(2)} oz / ${analysis.totalMassGrams.toFixed(1)} g)
Total Volume:       ${(analysis.totalVolumeMm3 / 1000).toFixed(2)} cm³ (${(analysis.totalVolumeMm3 / 16387.064).toFixed(3)} in³)
Center of Mass:     [X: ${analysis.centroid.x.toFixed(2)}, Y: ${analysis.centroid.y.toFixed(2)}, Z: ${analysis.centroid.z.toFixed(2)}] mm

ROTATION AXIS CONFIGURATION:
--------------------------------------------------------------------------------
Axis Name:          ${axis.name}
Origin Point:       [${axis.origin.x.toFixed(2)}, ${axis.origin.y.toFixed(2)}, ${axis.origin.z.toFixed(2)}] mm
Direction Vector:   [${axis.direction.x.toFixed(3)}, ${axis.direction.y.toFixed(3)}, ${axis.direction.z.toFixed(3)}]
Spin Direction:     ${axis.spinReversed ? 'Clockwise (CW)' : 'Counter-Clockwise (CCW)'}

COMBAT DYNAMICS @ ${analysis.targetRpm.toLocaleString()} RPM:
--------------------------------------------------------------------------------
Target Speed:       ${analysis.targetRpm.toLocaleString()} RPM (${analysis.angularVelocityRadS.toFixed(1)} rad/s)
Kinetic Energy:     ${analysis.kineticEnergyJoules.toFixed(1)} Joules (${(analysis.kineticEnergyJoules * 0.737562).toFixed(1)} ft·lbf)
Tip Radius:         ${analysis.tipRadiusMm.toFixed(1)} mm (${(analysis.tipRadiusMm / 25.4).toFixed(2)} in)
Cutting Diameter:   ${analysis.cuttingDiameterMm.toFixed(1)} mm (${(analysis.cuttingDiameterMm / 25.4).toFixed(2)} in)
Tip Speed:          ${analysis.tipSpeedMph.toFixed(1)} mph (${analysis.tipSpeedMPerS.toFixed(1)} m/s)
BattleBots Limit:   ${analysis.tipSpeedMph <= 250 ? 'PASS (Within 250 mph limit)' : 'ALERT (Exceeds 250 mph rule)'}

BALANCE & VIBRATION ANALYSIS:
--------------------------------------------------------------------------------
Eccentricity (e):   ${analysis.eccentricityMm.toFixed(3)} mm
Static Balance:     ${analysis.isStaticallyBalanced ? 'BALANCED (e < 0.05 mm)' : 'OFF-CENTER / IMBALANCED'}
Bearing Force:      ${analysis.radialImbalanceForceN.toFixed(1)} N (${(analysis.radialImbalanceForceN * 0.224809).toFixed(1)} lbf)

INERTIA TENSOR ABOUT COM (g·mm²):
--------------------------------------------------------------------------------
[ ${analysis.inertiaCom.Ixx.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Ixy.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Izx.toFixed(0).padStart(10)} ]
[ ${analysis.inertiaCom.Ixy.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Iyy.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Iyz.toFixed(0).padStart(10)} ]
[ ${analysis.inertiaCom.Izx.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Iyz.toFixed(0).padStart(10)}, ${analysis.inertiaCom.Izz.toFixed(0).padStart(10)} ]

================================================================================
Generated by LNCR-WEP_ANALYSIS · Combat Robotics Open Tool
================================================================================
`;

  const copyToClipboard = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadJson = () => {
    const data = {
      app: 'LNCR-WEP_ANALYSIS',
      timestamp: new Date().toISOString(),
      filename,
      material: {
        name: material.name,
        densityGPerCm3: material.densityGPerCm3,
      },
      axis,
      moi: {
        lb_in2: moiLbIn2,
        oz_in2: moiOzIn2,
        kg_m2: moiKgM2,
        g_cm2: moiGCm2,
      },
      mass: {
        grams: analysis.totalMassGrams,
        pounds: analysis.totalMassGrams * 0.00220462,
        ounces: analysis.totalMassGrams * 0.035274,
      },
      dimensions: {
        tipRadiusMm: analysis.tipRadiusMm,
        cuttingDiameterMm: analysis.cuttingDiameterMm,
        boundingBoxMm: analysis.boundingBox,
      },
      dynamics: {
        rpm: analysis.targetRpm,
        kineticEnergyJoules: analysis.kineticEnergyJoules,
        tipSpeedMph: analysis.tipSpeedMph,
        eccentricityMm: analysis.eccentricityMm,
        radialForceN: analysis.radialImbalanceForceN,
      },
      inertiaTensorCom: analysis.inertiaCom,
    };

    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `LNCR_${filename.replace(/\.[^/.]+$/, '')}_Analysis.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    const printWin = window.open('', '_blank');
    if (!printWin) return;
    printWin.document.write(`
      <html>
        <head>
          <title>LNCR Weapon Report - ${filename}</title>
          <style>
            body { font-family: monospace; white-space: pre-wrap; padding: 20px; font-size: 12px; color: #111; }
          </style>
        </head>
        <body>${reportText}</body>
      </html>
    `);
    printWin.document.close();
    printWin.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-fade-in">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl max-w-3xl w-full max-h-[88vh] flex flex-col shadow-2xl text-slate-200">
        <div className="flex items-center justify-between p-4 border-b border-slate-800">
          <div className="flex items-center gap-2 font-bold text-base text-slate-100">
            <FileText className="text-cyan-400" size={18} />
            <span>Weapon Engineering Report</span>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X size={18} />
          </button>
        </div>

        <div className="p-4 flex-1 overflow-y-auto">
          <pre className="font-mono text-xs bg-slate-950 p-4 rounded-xl border border-slate-800/80 text-cyan-300/90 overflow-x-auto whitespace-pre leading-relaxed select-all">
            {reportText}
          </pre>
        </div>

        <div className="p-4 border-t border-slate-800 flex items-center justify-between gap-2 flex-wrap">
          <div className="flex items-center gap-2">
            <button
              onClick={copyToClipboard}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium rounded-lg border border-slate-700 transition-colors"
            >
              {copied ? <Check size={14} className="text-emerald-400" /> : <Copy size={14} />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Text'}</span>
            </button>
            <button
              onClick={downloadJson}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium rounded-lg border border-slate-700 transition-colors"
            >
              <Download size={14} />
              <span>Download JSON</span>
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium rounded-lg border border-slate-700 transition-colors"
            >
              <Printer size={14} />
              <span>Print / PDF</span>
            </button>
            <button
              onClick={onClose}
              className="px-4 py-1.5 bg-cyan-500 hover:bg-cyan-400 text-slate-950 font-bold text-xs rounded-lg transition-colors"
            >
              Done
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
